#pragma once

#include "game.h"

#include <SDL.h>
#include <SDL_mixer.h>
#include <string>
#include <vector>

// Оболочка игры — всё, что происходит ДО симуляции: заставка студии
// (клеточное поле, из которого собирается TENEVIK GAMES), главное меню,
// комикс-пролог и экран генерации мира.
//
// Генерация мира занимает ~9 с (замер `./game --smoke`), поэтому она уходит в
// фоновый поток, а игрок в это время листает комикс. Правило §2 мастер-промпта:
// оболочка НИКОГДА не трогает глобальный `rng` симуляции — у неё свой генератор.
namespace Shell {

// Плейлист как «мешок»: случайная перестановка треков, играем её насквозь, потом
// тасуем заново. Так за круг звучат ВСЕ треки и ни один не повторяется подряд.
//
// ⚠️ Зерно берётся из `SDL_GetPerformanceCounter()`, а НЕ из константы: с
// фиксированным зерном каждый запуск давал одну и ту же последовательность, и
// игрок слышал вечно один и тот же трек. При этом правило §2.3 не нарушено —
// глобальный `rng` симуляции музыка по-прежнему не трогает, поэтому мир при
// одном seed остаётся побитово одинаковым.
struct MusicState {
    std::vector<int> order;   // текущая перестановка индексов плейлиста
    size_t next = 0;          // какой элемент перестановки играть следующим
    int lastPlayed = -1;      // чтобы стык двух перестановок не дал повтор
    unsigned int seed = 0;    // 0 = ещё не засеяно
};

// Заводит следующий трек, если музыка молчит. Зовётся каждый кадр и оболочкой,
// и главным циклом — состояние одно на весь сеанс, поэтому мешок общий.
void pumpMusic(MusicState& state, const std::vector<Mix_Music*>& playlist, bool soundOn);

enum Outcome {
    OUTCOME_QUIT = 0,   // игрок закрыл окно или выбрал EXIT
    OUTCOME_NEW_GAME,   // мир сгенерирован в фоне, `game` готов
    OUTCOME_LOAD_GAME   // сейв загружен в `game`
};

// Прогоняет оболочку целиком. Возвращает управление, когда `game` уже готов к
// симуляции (или игрок вышел). Блокирующая: внутри свой цикл событий.
//
//   window/renderer — окно игры (оболочка сама следит за ресайзом);
//   game            — мир, который оболочка сама инициализирует/загрузит;
//   starCount       — сколько звёзд генерировать (STAR_COUNT);
//   worldSeed       — зерно мира, кладётся в game.seed до генерации;
//   savePath        — путь к сейву (для пункта LOAD GAME);
//   soundOn         — сквозная настройка звука, меню её переключает;
//   playlist/music  — плейлист и его мешок-перестановка (общие с главным циклом);
//   autopilot       — `--shellsmoke`: сама себе жмёт «дальше», без звука, с
//                     потолком по времени. Прогоняет весь путь заставка→меню→
//                     комикс→загрузка→старт headless, чтобы оболочка попадала
//                     под ASan и в CI (в обычном `--smoke` она пропускается).
int run(SDL_Window* window, SDL_Renderer* renderer, Game& game, size_t starCount,
        unsigned int worldSeed, const std::string& savePath, bool& soundOn,
        const std::vector<Mix_Music*>& playlist, MusicState& music, bool autopilot = false);

}
