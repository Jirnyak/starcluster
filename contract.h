#pragma once
#include <vector>

enum class ContractType {
    Delivery,
    Courier,
    Scout,
    Bounty,
    Escort,
    Raid,
    ColonySupply
};

struct Contract {
    int id = 0;
    ContractType type = ContractType::Delivery;
    // --- Тир заказа (§24) ---------------------------------------------------
    // 0..1, НЕПРЕРЫВНО. Не ступеньки «мелкий/средний/крупный», а одно число,
    // выведенное из репутации у выдающей фракции: от него идут и масса груза,
    // и дальность, и множитель награды. Хранится в заказе, а не считается
    // заново, потому что репутация к моменту сдачи уже другая.
    double tier = 0.0;
    // Множитель ставки за тугой срок (1.0 — обычный заказ, >1 — срочный).
    // Виден на доске ДО взятия: риск оплачен вперёд, а не задним числом.
    double rushFactor = 1.0;
    int issuerFaction = -1;
    int originStar = -1;
    int targetStar = -1;
    int targetAgent = -1;
    int resource = -1;
    double amount = 0.0;
    double reward = 0.0;
    double deposit = 0.0;
    // (§46) НАДБАВКА НА ДОРОГУ. Заказчик оплачивает сгоревшее — но только тому,
    // кто привёз В СРОК. Ставка `CONTRACT_PAY_PER_YEAR` откалибрована (§23)
    // против свободного рейса НИЩЕГО игрока, а дорога дорожает вместе с
    // корпусом: замер по шести мирам — 45 строк из 48 (94%) убыточны по одному
    // топливу, типичная «награда 1 081 Cr при сгорающем на 4 643». Величина
    // фиксируется В МОМЕНТ ВЗЯТИЯ и по кораблю, который заказ берёт: так она
    // видна на доске до нажатия и не зависит от того, чем игрок в итоге полетел.
    double fuelAllowance = 0.0;
    double postedTime = 0.0;
    double deadline = 0.0;
    double risk = 0.0;
    double progress = 0.0;
    bool reportSignalPending = false;
    bool reportDelivered = false;
    bool escortArrived = false;
    int acceptedByAgent = -1;
    // Кто ФИЗИЧЕСКИ везёт груз (§24). Крупный заказ не влезает в один корпус,
    // поэтому при взятии он раскладывается по бортам игрока, стоявшим в системе
    // отправления, и сдать его можно только когда ВСЕ носители на месте.
    // Пусто — заказ везёт один `acceptedByAgent` (обычный случай).
    std::vector<int> carriers;
    // Цель заказа на голову УЖЕ сбита — в локальном полёте, своими руками (§34).
    // Без этого флага бой в микромире и доска заказов жили в разных играх:
    // заказ на пирата решался абстрактным сравнением боевой мощи в порту, а
    // то, что игрок только что разнёс этого самого пирата в бою, не значило
    // ничего.
    bool targetDown = false;
    bool completed = false;
    bool failed = false;
};
