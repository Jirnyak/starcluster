#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Ядро экономики: функции-нужды и матрица способностей элементов.
//
// Система нуждается НЕ в элементах, а в ФУНКЦИЯХ (топливо, конструкция,
// проводник, жизнеобеспечение...). Каждый элемент — кандидат на каждую функцию
// с качеством q в [0,1], которое ВЫВОДИТСЯ из уже существующего континуума
// ElementDefinition (октет: shellFill/nobleStability/реактивность; ядро:
// nuclearStability/пик железа; металличность; масса). Никаких частных случаев
// по элементам: нули получаются сами (у Og все q ~ 0, потому что физика).
//
// Спрос на конкретный элемент — следствие конкуренции кандидатов за функцию:
//   w(i,f)     = (q(i,f) / p(i))^SIGMA        — качество на кредит
//   share(i,f) = w(i,f) / SUM_j w(j,f)        — доля кандидата в функции
//   demand(i)  = SUM_f Need(f)*share(i,f)/q(i,f)
// Отсюда замещение: раскупили лидера -> его цена вверх -> доля уходит суррогату.
// ---------------------------------------------------------------------------

enum EconFunction {
    EF_FUSION = 0,   // термоядерное топливо (лёгкие ядра до пика железа)
    EF_FISSION,      // делящееся топливо (тяжёлые ядра за пиком)
    EF_STRUCT,       // конструкционный материал
    EF_CONDUCT,      // проводники / электроника
    EF_CATALYST,     // катализ / химическая промышленность
    EF_LIFE,         // жизнеобеспечение (лёгкие летучие, органогены)
    EF_REACT,        // реагенты: окислители/восстановители
    EF_SHIELD,       // радиационная защита / балласт (плотные стабильные)
    EF_REFRACT,      // жаропрочность (тугоплавкие металлы)
    EF_INERT,        // химически стойкое: благородные металлы и инертные среды
    EF_COUNT
};

// Эластичность замещения: чем выше, тем резче рынок садится на лучшего
// кандидата и тем драматичнее переключение на суррогат при дефиците.
extern const double ECON_SIGMA;

// Целевой запас (лет потребления), к которому рынок тянет цену.
extern const double ECON_TARGET_COVERAGE;

// Технологический порог качества: кандидат ниже него не годится ни за какие деньги.
extern const double ECON_QUALITY_FLOOR;

// Якорь уровня цен: сколько кредитов стоит единица услуги идеального кандидата.
// Доли замещения зависят только от ОТНОСИТЕЛЬНЫХ цен, поэтому номинальный
// уровень нужно закрепить явно — иначе он свободно дрейфует в пол или потолок.
extern const double ECON_CREDITS_PER_SERVICE;

// Эластичность спроса по цене услуги: насколько общество урезает потребление,
// когда услуга дорожает. Без неё нужда неутолима и цена уходит в бесконечность.
extern const double ECON_DEMAND_ELASTICITY;

// Опорная цена элемента по его лучшей услуге (без учёта местного дефицита).
double econAnchorPrice(int elementIndex);

const char* econFunctionCode(int f);   // 3 буквы — влезает в клетку таблицы
const char* econFunctionName(int f);   // полное имя для панели

// Качество элемента как кандидата на функцию, [0,1].
// Нормировано по столбцу: лучший кандидат функции = 1.0.
double econQuality(int elementIndex, int functionIndex);
// q^SIGMA — предвычислено (в горячем цикле рынка pow звать нельзя).
double econQualityPow(int elementIndex, int functionIndex);
// 1/q (0, если q пренебрежимо мало).
double econQualityInv(int elementIndex, int functionIndex);

int econPrimaryFunction(int elementIndex);   // лучшая функция элемента (-1 если бесполезен)
double econPrimaryQuality(int elementIndex);

// Профиль нужд экономической роли: EF_COUNT долей, сумма = 1.
const double* econRoleNeedProfile(const std::string& role);
