#pragma once
#include <string>
#include <vector>

class ClusterStar;

// ---------------------------------------------------------------------------
// ЭКЗОТИЧЕСКАЯ МАТЕРИЯ — второй, хайтек-этаж торговли (§31).
//
// Таблица элементов кончается там же, где кончается ХИМИЯ: у неё есть предел,
// заданный кривой связи, и максимум, который можно вытащить из ядра, — около
// 8 МэВ на нуклон. Всё, чем живёт поздняя игра, лежит ЗА этим пределом, и это
// не «редкие товары», а три разных состояния вещества, каждое со своим местом
// рождения:
//
//   ANTIMATTER   антиводород. Энергия аннигиляции — 938 МэВ на нуклон, в сто с
//                лишним раз больше синтеза. Не добывается: ПРОИЗВОДИТСЯ, и
//                стоит ровно столько, сколько стоит энергия на её производство.
//                Значит, рождается там, где энергии много: яркая звезда плюс
//                промышленность.
//   NEUTRONIUM   вырожденное вещество нейтронной звезды. Не производится
//                вообще — только собирается с поверхности мёртвой звезды или из
//                аккреционного диска. Плотность делает его лучшей бронёй,
//                какая бывает.
//   CONDENSATE   когерентный конденсат — подложка хромокора. Квантовая
//                когерентность живёт только в холоде и покое: белый карлик,
//                холодная звезда, высокая металличность.
//
// Ключевое свойство: у каждого вещества СВОЙ редкий тип звезды. Нейтронных
// звёзд в скоплении около 0.8%, белых карликов 0.5% — то есть источники надо
// ИСКАТЬ, и разведка впервые получает поздний смысл.
//
// Модель рынка здесь другая, чем у элементов, и намеренно: обычный рынок —
// живая система замещения, которая тикает каждый такт по всем 8192 звёздам.
// Экзотика тикать не может (её касается ОДИН игрок, и держать ради него ещё
// один проход по скоплению — глупость), поэтому запас считается ЛЕНИВО: цель
// — чистая функция звезды, отклонение от цели релаксирует к нулю за
// EXOTIC_RECOVERY_YEARS, и в сейв попадают только те звёзды, где игрок реально
// торговал.
// ---------------------------------------------------------------------------

enum ExoticKind {
    EX_ANTIMATTER = 0,
    EX_NEUTRONIUM = 1,
    EX_CONDENSATE = 2,
    EX_COUNT = 3
};

struct ExoticDef {
    const char* symbol;      // короткий код для таблиц: AM / NM / QC
    const char* name;        // полное имя в интерфейсе
    double basePrice;        // опорная цена за единицу, Cr
    double unitMass;         // масса торговой единицы (в тех же единицах, что и груз)
    const char* blurb;       // одна строка «зачем оно»
};

const std::vector<ExoticDef>& exoticDefs();

// Сколько лет запас идёт от нуля к цели. Источник восстанавливается на глазах
// одного игрока: рейс длится десятки лет, значит и восстановление обязано
// мериться сотнями, иначе «выработал источник» ничего не значит.
extern const double EXOTIC_RECOVERY_YEARS;

// ЦЕЛЕВОЙ запас вещества на звезде — чистая функция звезды, без состояния.
// 0 означает «здесь этого нет и не будет»: рынок экзотики есть далеко не везде.
double exoticTargetStock(const ClusterStar& star, int kind);

// Есть ли на звезде рынок экзотики хоть по одному веществу.
bool exoticStarHasMarket(const ClusterStar& star);

// Сила ИСТОЧНИКА: сколько вещества эта звезда даёт сама. 0 — здесь его не
// рождается, и купить можно только то, что кто-то привёз. Наружу вынесено ради
// регрессии: «у каждого вещества есть свой источник» — свойство мира, которое
// обязано проверяться, а не подразумеваться.
double exoticStockSourceStrength(const ClusterStar& star, int kind);

// Цена единицы при ТЕКУЩЕМ запасе. Дефицит дорог, завал дёшев: отношение
// stock/target входит в цену степенным законом, поэтому выбранный подчистую
// источник дорожает, а не кончается «в ноль» скачком.
//   priceLevel — денежный уровень скопления (Game::clusterPriceLevel).
double exoticPriceAt(const ClusterStar& star, int kind, double stock, double priceLevel);

// СРЕДНЯЯ цена исполнения сделки объёмом units: цена ползёт ПО ХОДУ сделки, как
// и на обычном рынке (Market::executionPrice). Крупная закупка сама себе портит
// котировку — иначе один рейс к богатому источнику печатал бы деньги.
double exoticExecutionPrice(const ClusterStar& star, int kind, double stock,
                            double priceLevel, double units, bool selling);

// Куда девается вещество, проданное игроком: оно вливается в местный запас и
// сбивает цену. Обратная операция — покупка — запас уменьшает.
double exoticStockAfterTrade(const ClusterStar& star, int kind, double stock, double deltaUnits);

// Релаксация запаса к цели за прошедшие годы (ленивое «догоняние» вместо тика).
double exoticRelaxStock(const ClusterStar& star, int kind, double stock, double years);

// --- Аннигиляционный катализ (см. §31.3) -----------------------------------
// Энергия аннигиляции на нуклон, МэВ. Ровно две энергии покоя нуклона: пара
// «нуклон + антинуклон» уходит в излучение целиком.
extern const double EXOTIC_ANNIHILATION_MEV;
