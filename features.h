#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Хромокоры — бесконечно масштабируемые статы-мультипликаторы (design.md §2).
// Все множители >= 1.0. Часть эффектов "запекается" в поля корабля при
// получении ядра (материалы -> трюм/корпус, кинематика -> скорость,
// тактика -> оружие), часть применяется в точке использования в новом коде
// (харизма -> цены, сенсоры -> дальность, удача -> RNG, интеллект -> прогресс).
// ---------------------------------------------------------------------------
struct TechState {
    double intellect = 1.0;   // темп накопления исследований + пассив к прочим
    double charisma = 1.0;    // цены к номиналу (ниже тарифы/маржа)
    double materials = 1.0;   // прочность корпуса и грузоподъёмность
    double tactics = 1.0;     // урон тем же вооружением
    double kinematics = 1.0;  // скорость перелётов
    double sensors = 1.0;     // дальность радаров/обнаружения аномалий
    double luck = 1.0;        // подкрутка исходов случайных событий
    int cores = 0;            // всего установлено хромокоров
    double research = 0.0;    // накоплено к следующему ядру
};

// Индексы статов для случайной выдачи/сериализации (стабильны — не менять порядок).
enum TechStat {
    TECH_INTELLECT = 0,
    TECH_CHARISMA = 1,
    TECH_MATERIALS = 2,
    TECH_TACTICS = 3,
    TECH_KINEMATICS = 4,
    TECH_SENSORS = 5,
    TECH_LUCK = 6,
    TECH_STAT_COUNT = 7
};

// ---------------------------------------------------------------------------
// Динамические рыночные события (plans_5).
// ---------------------------------------------------------------------------
enum class MarketEventKind {
    TechBoom = 0,        // всплеск спроса на продвинутые/редкие элементы
    WarDemand = 1,       // военный спрос на металлы/топливо
    Famine = 2,          // голод: спрос на летучие/биоресурсы
    ProductionGlut = 3,  // перепроизводство: обвал цен
    ResourceStrike = 4,  // забастовка/истощение: скачок цен
    Plague = 5           // эпидемия: шок спроса
};

struct MarketEvent {
    int star = -1;
    MarketEventKind kind = MarketEventKind::TechBoom;
    double startTime = 0.0;
    double endTime = 0.0;
    double magnitude = 3.0;       // сила множителя
    bool announced = false;
    std::vector<int> elements;    // затронутые индексы элементов
};

// ---------------------------------------------------------------------------
// Аномалии / дереликты (plans_10).
// ---------------------------------------------------------------------------
enum class AnomalyKind {
    DerelictShip = 0,     // покинутый корабль: груз + обломки
    AncientCache = 1,     // древний тайник: кредиты + редкие элементы
    ChromocoreVault = 2,  // хранилище с хромокором (редко, у пульсаров)
    NebulaEcho = 3,       // сенсорное эхо: наводка/кредиты
    IonStorm = 4          // ионный шторм: опасность для корпуса
};

struct Anomaly {
    double x = 0.0, y = 0.0, z = 0.0;
    AnomalyKind kind = AnomalyKind::DerelictShip;
    bool discovered = false;   // обнаружена сенсорами игрока
    bool resolved = false;     // обследована/зачищена
    int lootElement = -1;      // индекс элемента добычи
    double lootAmount = 0.0;
    double credits = 0.0;
    int chromocoreStat = -1;   // какой стат TechState (0..6), если хранилище
    double hazard = 0.0;       // риск урона корпусу
    int nearStar = -1;         // ближайшая звезда (для названия/новостей)
    std::string name;
};

// ---------------------------------------------------------------------------
// Лента новостей — скользящий журнал заметных событий.
// kind: 0 инфо, 1 рынок, 2 бой, 3 открытие, 4 прогресс.
// ---------------------------------------------------------------------------
struct NewsItem {
    std::string text;
    double time = 0.0;
    int kind = 0;
};
