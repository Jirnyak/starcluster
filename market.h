#pragma once
#include <vector>
#include <string>
#include "resource.h"

// Локальный рынок ресурсов.
//
// Цена НЕ приписана элементу: она рождается из конкуренции кандидатов за
// функции-нужды системы (см. econ.h). Запас тает от потребления, растёт от
// добычи; цена тянется туда, где спрос сходится с предложением. Раскупили
// лидера — доля спроса перетекает на суррогат, и волна идёт по семейству.
class Market {
public:
    std::vector<Resource> supply; // Запас на рынке (масса)
    std::vector<Resource> demand; // Годовой спрос (для совместимости — масса)
    std::vector<double> prices;   // Цены по индексам элементов
    std::vector<double> productionRate; // Местная добыча/производство, масса в год
    std::vector<double> demandRate;     // Потребление из модели замещения, масса в год
    std::vector<double> eventMul; // временные ценовые множители (рыночные события)
    std::vector<double> demandNoise; // лёгкая рябь предпочтений
    std::vector<double> needs;    // EF_COUNT: услуг в год, которых требует система
    double serviceCostAvg = 0.0;  // средняя цена единицы услуги на этом рынке
    std::vector<double> rationing;// EF_COUNT: доля нужды, которую общество ещё может себе позволить
    std::vector<double> pref;     // мягкая локальная преференция по элементам
    std::string role;
    double strain = 0.0;          // 0..1 — доля незакрытых нужд (система чахнет)
    double tradeAccess = 0.5;     // 0..1 — насколько плотно систему обслуживают чужие торговцы

    // Масштаб хозяйства, с которым рынок был засеян в последний раз. Нужен,
    // чтобы понять, насколько система с тех пор выросла (см. rescale).
    double seededScale = 0.0;

    Market();
    void seed(const std::vector<Resource>& localResources, const std::vector<double>& demandBias, const std::string& role_, double population, double industry);

    // Пересчёт РАЗМЕРА хозяйства без сброса рынка (§36).
    //
    // ⚠️ До этой функции `needs` и `productionRate` задавались ТОЛЬКО в seed() —
    // то есть масштаб экономики системы был заморожен на момент генерации мира.
    // Колония растила `star.population` и `star.industry`, стройка поднимала
    // инфраструктуру, а рынок этого не замечал вовсе: система с миллиардом
    // жителей потребляла столько же, сколько посёлок, из которого она выросла.
    // Петля «вложился в колонию → она больше производит и больше потребляет»
    // была разомкнута, и доход владельца (доля от оборота, §18) не рос никогда.
    //
    // Возвращает true, если масштаб реально изменился. Цены, запасы и события
    // не трогаются — двигается только размер нужды и добычи.
    bool rescale(double population, double industry);
    void update(double dt);
    void updatePrices(); // Один шаг релаксации цен без движения запасов
    double pricePressure() const;

    // Сделка на этом рынке: deltaUnits > 0 — товар пришёл (продажа игроком),
    // < 0 — ушёл (закупка). Двигает и запас, и цену — рынок имеет ГЛУБИНУ,
    // поэтому крупный рейс сам портит себе цену.
    void applyTrade(int elementIndex, double deltaUnits);

    // СРЕДНЯЯ цена исполнения сделки объёмом `units`. Раньше весь груз уходил по
    // цене ДО сделки, а `applyTrade` двигал цену только ПОСЛЕ — то есть крупный
    // рейс продавался по пику и проскальзывания не было вовсе (замер: один рейс
    // давал 44x капитала). Теперь цена движется ПО ХОДУ сделки: интегрируем ту же
    // экспоненциальную реакцию, которую применяет applyTrade, по объёму.
    //   продажа: p(x) = p0·exp(−k·x/depth) ⇒ avg = p0·(depth/kN)·(1 − e^(−kN/depth))
    //   покупка: p(x) = p0·exp(+k·x/depth) ⇒ avg = p0·(depth/kN)·(e^(+kN/depth) − 1)
    // Ни одной новой константы: k и depth — те же, что в applyTrade. Глубокий
    // рынок почти не проскальзывает, тонкий — сильно, поэтому важен уже не только
    // размер спреда, но и размер рынка.
    double executionPrice(int elementIndex, double units, bool selling) const;

    // Глубина рынка по элементу (годовой оборот за срок целевого запаса).
    double depthOf(int elementIndex) const;

    // --- Чтение модели (для UI и ИИ) ---
    // Текущая цена одной единицы услуги f: минимум p(i)/q(i,f) по кандидатам.
    double serviceCost(int functionIndex) const;
    // Справедливая цена элемента: чего он стоит по своей лучшей услуге.
    double fairPrice(int elementIndex) const;
    // Доля элемента в закрытии функции при текущих ценах, [0,1].
    double marketShare(int elementIndex, int functionIndex) const;
    // Запас в годах текущего потребления (большое число = завал).
    double coverageYears(int elementIndex) const;
    // Индекс функции, которой этот рынок в основном закрывает данный элемент.
    int dominantNeedFunction() const;
};

// Опорная цена скопления: чего элемент стоит на «типичном» рынке.
// Отклонение локальной цены от опорной — сигнал арбитража для игрока.
double marketReferencePrice(int elementIndex);

// Денежный уровень СКОПЛЕНИЯ: отношение текущей стоимости услуг к базовой.
// 1.0 = как в начале, >1 = скопление подорожало. Входит в ценовой дрейф каждого
// рынка и держит ставку лицензионного тарифа.
//
// Это НЕ состояние рынка и не накопитель: авторитетное значение живёт в
// `Game::clusterPriceLevel`, сохраняется в сейв и пересчитывается РАЗ В
// ТЫСЯЧЕЛЕТИЕ на официальной сверке (§15.4). Здесь только кэш, который владелец
// проталкивает вниз каждый такт, — поэтому рынок остаётся чистой функцией своих
// данных и ничего не накапливает у себя за спиной.
//
// Раньше уровень копился прямо в `Market::update` в файловом глобале: он не
// сохранялся, не сбрасывался при загрузке и вдобавок засорялся синтетическими
// рынками из `buildReferencePrices`. Одна и та же партия давала разную ставку
// тарифа в свежем процессе и после часа игры.
void marketSetClusterLevel(double level);
double marketClusterLevel();

// Множитель СРЕДНЕЙ цены исполнения для сделки объёмом `units` на рынке глубиной
// `depth`: <1 при продаже (сам сбиваешь цену), >1 при покупке (сам её разгоняешь).
// Вынесен отдельно, чтобы биржевая сводка могла ОЦЕНИТЬ выручку на чужом рынке,
// глубина которого игроку неизвестна, тем же законом, по которому сделка потом
// реально исполнится.
double marketExecutionFactor(double units, double depth, bool selling);
