#pragma once

#include <string>

// Локализация интерфейса.
//
// Игра рисует ВЕСЬ текст через одну функцию — `UI::drawText` (render2d.cpp).
// Поэтому перевод сделан не правкой сотен мест вызова, а словарём, который
// применяется в самой drawText: строка приходит уже собранной (с подставленными
// числами через snprintf), а словарь заменяет в ней английские слова и обороты.
// Числа, символы элементов, имена звёзд и пунктуация остаются нетронутыми.
//
// Порядок разбора в `tr`:
//   1. точное совпадение всей строки (длинные фразы и форматы с %s);
//   2. жадное совпадение оборота из нескольких слов (разделённых пробелами);
//   3. пословно; несовпавшее слово остаётся как есть.
//
// ⚠️ Двухбуквенные ключи опасны: они сталкиваются с символами элементов
// (In, No, Se, Ta, Cr...). В словаре их нет намеренно — см. комментарий в
// i18n.cpp у таблицы WORDS.
namespace I18N {

enum Lang {
    LANG_EN = 0,
    LANG_RU = 1
};

Lang lang();
void setLang(Lang l);

// Перевод на текущий язык. На LANG_EN возвращает исходную строку без работы.
// Результат кэшируется, поэтому вызывать можно хоть каждый кадр.
const std::string& tr(const std::string& s);

// Читает/пишет выбранный язык рядом с сейвом. Пустой/битый файл — не ошибка:
// остаётся английский, и меню предложит выбор.
void loadPreference(const std::string& path);
void savePreference(const std::string& path);

}  // namespace I18N
