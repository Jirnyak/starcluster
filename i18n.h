#pragma once

#include <string>

// Локализация интерфейса.
//
// Игра рисует ВЕСЬ текст через одну функцию — `UI::drawText` (render2d.cpp).
// Поэтому перевод сделан не правкой сотен мест вызова, а словарём, который
// применяется в самой drawText: строка приходит уже собранной (с подставленными
// числами через snprintf), а словарь заменяет в ней английские слова и обороты.
// Числа, символы элементов, имена звёзд и пунктуация остаются нетронутыми.
//
// Порядок разбора в `tr`:
//   1. точное совпадение всей строки (длинные фразы и форматы с %s);
//   2. жадное совпадение оборота из нескольких слов (разделённых пробелами);
//   3. пословно; несовпавшее слово остаётся как есть.
//
// ⚠️ Двухбуквенные ключи опасны: они сталкиваются с символами элементов
// (In, No, Se, Ta, Cr...). В словаре их нет намеренно — см. комментарий в
// i18n.cpp у таблицы WORDS.
namespace I18N {

enum Lang {
    LANG_EN = 0,
    LANG_RU = 1
};

Lang lang();
void setLang(Lang l);

// Перевод на текущий язык. На LANG_EN возвращает исходную строку без работы.
// Результат кэшируется, поэтому вызывать можно хоть каждый кадр.
const std::string& tr(const std::string& s);

// Имена собственные (основы имён систем: «VAREN» из «Varen-417»). В отличие от
// словаря интерфейса, который зашит в i18n.cpp, реестр наполняется на лету —
// при генерации скопления и при загрузке сейва (Cluster::registerNames).
// Благодаря этому имя системы переводится там же, где и всё остальное: внутри
// drawText, — и попадает в кириллицу разом в заказах, журнале, новостях и на
// карте, без правки сотен мест вызова.
//
// Регистрация с ключом, который уже что-то значит в интерфейсе, игнорируется:
// система по имени MINE не должна превращать себя в «ШАХТУ».
//
// ⚠️ Зовётся ИЗ ФОНОВОГО ПОТОКА (мир генерируется, пока главный поток рисует
// комикс и переводит его подписи), поэтому таблицы i18n под замком, а кэш
// переводов — свой у каждого потока. См. комментарий у dictMutex в i18n.cpp.
void registerProperNoun(const std::string& en, const std::string& ru);
void clearProperNouns();

// Есть ли слово (или оборот) в словаре интерфейса. Генератор имён спрашивает
// ЗАРАНЕЕ и перекатывает имя при совпадении — см. starNameFor в cluster.cpp.
bool isInterfaceWord(const std::string& s);

// Совпадают ли спецификаторы формата у английского ключа и русского перевода.
// Перестановка «%s» и «%.2f» местами роняет игру внутри snprintf — см. i18n.cpp.
// Проверяется в `make balance`; `firstBad` получает первый разошедшийся ключ.
bool formatSpecsConsistent(std::string* firstBad);

// Читает/пишет выбранный язык рядом с сейвом. Пустой/битый файл — не ошибка:
// остаётся английский, и меню предложит выбор.
void loadPreference(const std::string& path);
void savePreference(const std::string& path);

}  // namespace I18N
