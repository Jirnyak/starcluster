// --- Лицензионная квота оборота ------------------------------------------
// Лицензия торговца не бесплатна: с каждой продажи удерживается тариф, и за
// отчётный период игрок обязан наторговать столько, чтобы уплаченных тарифов
// набралось не меньше квоты. Не набрал — лицензию отзывают, торговля
// замораживается до выкупа.
//
// Период — ТЫСЯЧЕЛЕТИЕ, и это не произвол: скопление ~100 световых лет в
// поперечнике, поэтому цены в разных его концах расходятся на века, и сверить
// их можно лишь релятивистской корректировкой раз в тысячу лет. Тогда же
// пересматривают и квоты. При «1 игровой год = 1 реальная секунда» это около
// 17 минут игры на скорости x1 — дедлайн ощутим, но не гонит.
//
// Квота растёт на 1% за период: скопление богатеет, планка ползёт вверх, и
// сидеть на одном отработанном маршруте вечно не выйдет.
//
// Планка первого тысячелетия — 10 000, и ставка — РОВНО 10%. Оба числа выбраны
// НЕ по замеру, а ради устного счёта игрока: «отдаю десятую часть с продажи» и
// «до квоты осталось столько-то тысяч» считаются в уме, без калькулятора.
// Читаемость шкалы здесь признана важнее прежнего design point.
//
// ⚠️ Прежний инвариант был другой: планка задавалась числом РЕЙСОВ (~120 за
// период), и при каждом пересчёте масштаба её двигали по замеру, а не по
// интуиции:
//   10 000 при деревенской экономике             => ~123 рейса
//   65 000 после пересчёта масштаба §17          => ~122 рейса (тариф 533/рейс)
//   40 000 после оживления ставки §19            => ~120 рейсов (тариф 332/рейс)
//   10 000 при ставке 0.10 (решение пользователя) => ~24 рейса
// То есть квота теперь закрывается за четверть периода, и остаток тысячелетия
// игрока ничто не подгоняет. Это сознательный размен, а не потерянный расчёт:
// вернёшь строгость — считай по рейсам, а не по кредитам.
const double LICENCE_PERIOD_YEARS = 1000.0;      // релятивистская корректировка рынка
const double LICENCE_QUOTA_BASE = 10000.0;       // квота первого тысячелетия (~24 рейса)
const double LICENCE_QUOTA_GROWTH = 1.01;        // +1% за каждый прожитый период
// Квота линейна по числу лицензий: ОДНА ЛИЦЕНЗИЯ — ОДНА КВОТА, и всё.
// Было 0.8 за каждую сверх первой (2 лицензии => 1.8 квоты), то есть флот давал
// скрытую скидку и планку приходилось считать в столбик. Решение пользователя —
// та же логика, что и в §21: шкала должна считаться в уме. Три лицензии — три
