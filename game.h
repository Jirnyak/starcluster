//
// Главное: это единственный способ ИГРАТЬ в макро-симуляцию. Фракции воюют,
// теряют системы, беднеют от выплат за головы — до сих пор игрок мог только
// смотреть. Теперь на этом можно заработать, а можно и разориться.
