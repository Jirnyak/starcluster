// Строка ЖУРНАЛА. Раньше журнал был чистой кассовой лентой: «[ГОД] @ система
// : ±N Cr» и ничего больше. По ней нельзя было понять, ЧТО игрок сейчас везёт
// и куда, — а именно это и терялось: взял заказ, улетел, забыл. Поэтому у
// строки появился ВИД: касса остаётся кассой, а заказы пишутся отдельными
